"""
PDF exporter — generates downloadable PDF documents from playlist content.

Creates well-formatted PDFs containing notes, flashcards, and quiz questions
using ReportLab.
"""

import io
import logging
from datetime import datetime, timezone

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle,
    PageBreak, HRFlowable,
)
from reportlab.lib.enums import TA_CENTER, TA_LEFT

logger = logging.getLogger(__name__)


def _get_styles():
    """Get custom paragraph styles for the PDF."""
    styles = getSampleStyleSheet()

    styles.add(ParagraphStyle(
        name="CustomTitle",
        parent=styles["Title"],
        fontSize=24,
        spaceAfter=30,
        textColor=colors.HexColor("#6D28D9"),
    ))

    styles.add(ParagraphStyle(
        name="SectionHeader",
        parent=styles["Heading1"],
        fontSize=16,
        spaceAfter=12,
        spaceBefore=20,
        textColor=colors.HexColor("#4C1D95"),
    ))

    styles.add(ParagraphStyle(
        name="SubHeader",
        parent=styles["Heading2"],
        fontSize=13,
        spaceAfter=8,
        spaceBefore=12,
        textColor=colors.HexColor("#5B21B6"),
    ))

    styles.add(ParagraphStyle(
        name="BodyText_Custom",
        parent=styles["BodyText"],
        fontSize=10,
        spaceAfter=6,
        leading=14,
    ))

    styles.add(ParagraphStyle(
        name="FlashcardQ",
        parent=styles["BodyText"],
        fontSize=10,
        spaceAfter=2,
        textColor=colors.HexColor("#1E40AF"),
        fontName="Helvetica-Bold",
    ))

    styles.add(ParagraphStyle(
        name="FlashcardA",
        parent=styles["BodyText"],
        fontSize=10,
        spaceAfter=8,
        leftIndent=20,
    ))

    return styles


def generate_pdf(
    playlist_title: str,
    notes: list[dict] = None,
    flashcards: list[dict] = None,
    quizzes: list[dict] = None,
) -> bytes:
    """
    Generate a PDF document from playlist content.

    Args:
        playlist_title: Title of the playlist
        notes: List of note dicts {content, note_type, video_title}
        flashcards: List of flashcard dicts {question, answer, difficulty, topic}
        quizzes: List of quiz dicts {question, options, correct_answer, explanation}

    Returns:
        PDF file as bytes
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=0.75 * inch,
        leftMargin=0.75 * inch,
        topMargin=0.75 * inch,
        bottomMargin=0.75 * inch,
    )

    styles = _get_styles()
    story = []

    # ── Title Page ─────────────────────────────────────────────────
    story.append(Spacer(1, 2 * inch))
    story.append(Paragraph(f"📚 {playlist_title}", styles["CustomTitle"]))
    story.append(Spacer(1, 0.25 * inch))
    story.append(Paragraph("Generated by Ytutor AI", styles["BodyText_Custom"]))
    story.append(Paragraph(
        f"Date: {datetime.now(timezone.utc).strftime('%B %d, %Y')}",
        styles["BodyText_Custom"],
    ))
    story.append(PageBreak())

    # ── Notes Section ──────────────────────────────────────────────
    if notes:
        story.append(Paragraph("📝 Study Notes", styles["SectionHeader"]))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#8B5CF6")))
        story.append(Spacer(1, 0.2 * inch))

        for note in notes:
            note_type = note.get("note_type", "detailed").title()
            story.append(Paragraph(f"{note_type} Notes", styles["SubHeader"]))

            # Convert markdown-ish content to paragraphs
            content = note.get("content", "")
            for line in content.split("\n"):
                line = line.strip()
                if not line:
                    story.append(Spacer(1, 6))
                elif line.startswith("# "):
                    story.append(Paragraph(line[2:], styles["SubHeader"]))
                elif line.startswith("## "):
                    story.append(Paragraph(line[3:], styles["SubHeader"]))
                elif line.startswith("- ") or line.startswith("* "):
                    story.append(Paragraph(f"• {line[2:]}", styles["BodyText_Custom"]))
                else:
                    # Escape XML special characters
                    line = line.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                    story.append(Paragraph(line, styles["BodyText_Custom"]))

            story.append(Spacer(1, 0.3 * inch))

    # ── Flashcards Section ─────────────────────────────────────────
    if flashcards:
        story.append(PageBreak())
        story.append(Paragraph("🃏 Flashcards", styles["SectionHeader"]))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#8B5CF6")))
        story.append(Spacer(1, 0.2 * inch))

        for i, card in enumerate(flashcards, 1):
            q = card.get("question", "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            a = card.get("answer", "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            difficulty = card.get("difficulty", "medium").title()

            story.append(Paragraph(f"Q{i}. {q} [{difficulty}]", styles["FlashcardQ"]))
            story.append(Paragraph(f"A: {a}", styles["FlashcardA"]))

    # ── Quiz Section ───────────────────────────────────────────────
    if quizzes:
        story.append(PageBreak())
        story.append(Paragraph("❓ Quiz Questions", styles["SectionHeader"]))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#8B5CF6")))
        story.append(Spacer(1, 0.2 * inch))

        for i, quiz in enumerate(quizzes, 1):
            q = quiz.get("question", "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            story.append(Paragraph(f"{i}. {q}", styles["FlashcardQ"]))

            options = quiz.get("options")
            if options:
                for opt in options:
                    opt_text = str(opt).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                    story.append(Paragraph(f"    {opt_text}", styles["BodyText_Custom"]))

            correct = quiz.get("correct_answer", "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            story.append(Paragraph(f"✅ Answer: {correct}", styles["FlashcardA"]))

            explanation = quiz.get("explanation", "")
            if explanation:
                explanation = explanation.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                story.append(Paragraph(f"💡 {explanation}", styles["BodyText_Custom"]))

            story.append(Spacer(1, 8))

    # Build PDF
    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()

    logger.info(f"Generated PDF: {len(pdf_bytes)} bytes")
    return pdf_bytes
